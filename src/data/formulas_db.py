def get_formula_dict() -> dict[str, FormulaInfo]:
    """返回方剂名→信息的字典"""
    return {f.name: f for f in FORMULAS}


def get_all_herbs() -> list[str]:
    """返回所有药材列表（去重）"""
    seen = set()
    for f in FORMULAS:
        for h in f.herbs:
            if h not in seen:
                seen.add(h)
                yield h
    return list(seen)


def get_herb_formulas() -> dict[str, list[str]]:
    """返回药材→方剂列表的字典"""
    result: dict[str, list[str]] = {}
    for f in FORMULAS:
        for h in f.herbs:
            if h not in result:
                result[h] = []
            result[h].append(f.name)
    return result


def get_formula_by_clause(clause_id: int) -> list[FormulaInfo]:
    """返回某条文相关的方剂"""
    return [f for f in FORMULAS if f.clause_id == clause_id]
